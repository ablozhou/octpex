package brain

import (
	"context"
	"errors"
	"fmt"
	"octpex/pkg/protocol"
	"strings"
	"sync"
	"time"
)

// DecisionType specifies the strategic arbitration outcome from Octo-Brain.
type DecisionType string

const (
	DecisionSynthesizeDynamicTool DecisionType = "SYNTHESIZE_DYNAMIC_TOOL" // Brain writes script and registers dynamic MCP tool
	DecisionReroutePeer           DecisionType = "REROUTE_PEER"            // Brain reroutes to a different specialized arm
	DecisionSuspendHITL           DecisionType = "SUSPEND_HITL"            // High-risk or policy conflict requires human approval
	DecisionAbort                 DecisionType = "ABORT"                   // Unrecoverable task failure
)

// PlanStep represents a single node in the global orchestration DAG.
type PlanStep struct {
	StepID           string   `json:"step_id"`
	TargetCapability string   `json:"target_capability"`
	Dependencies     []string `json:"dependencies,omitempty"` // StepIDs that must finish before this step
	Description      string   `json:"description"`
}

// PlanDAG represents a deterministic or dynamic plan generated by the Brain.
type PlanDAG struct {
	PlanID    string     `json:"plan_id"`
	Goal      string     `json:"goal"`
	Steps     []PlanStep `json:"steps"`
	CreatedAt time.Time  `json:"created_at"`
}

// HITLRequest describes an action suspended pending human-in-the-loop sign-off.
type HITLRequest struct {
	RequestID   string         `json:"request_id"`
	SessionID   string         `json:"session_id"`
	Description string         `json:"description"`
	RiskLevel   string         `json:"risk_level"` // LOW, MEDIUM, CRITICAL
	ContextData map[string]any `json:"context_data"`
	CreatedAt   time.Time      `json:"created_at"`
}

// ArbitrationDecision is the strategic resolution returned by Octo-Brain when an Arm escalates.
type ArbitrationDecision struct {
	DecisionID          string                    `json:"decision_id"`
	Decision            DecisionType              `json:"decision"`
	Reason              string                    `json:"reason"`
	SynthesizedToolCode string                    `json:"synthesized_tool_code,omitempty"`
	DynamicToolName     string                    `json:"dynamic_tool_name,omitempty"`
	NextEnvelope        *protocol.NervousEnvelope `json:"next_envelope,omitempty"`
	HITLRequest         *HITLRequest              `json:"hitl_request,omitempty"`
}

// GlobalOrchestratorSPI defines the high-level reasoning and arbitration interface of Octo-Brain.
type GlobalOrchestratorSPI interface {
	Plan(ctx context.Context, goal string, contextData map[string]any) (*PlanDAG, error)
	Arbitrate(ctx context.Context, escalation *protocol.EscalationPayload) (*ArbitrationDecision, error)
	SuspendForHITL(ctx context.Context, sessionID string, approvalReq *HITLRequest) error
	ResumeFromHITL(ctx context.Context, requestID string, approved bool, feedback string) (*protocol.NervousEnvelope, error)
}

// FrontierLLMProvider abstracts the cloud frontier reasoning model (e.g. Gemini, Claude, GPT).
type FrontierLLMProvider interface {
	GenerateDAG(ctx context.Context, goal string) (*PlanDAG, error)
	SolveEscalation(ctx context.Context, payload *protocol.EscalationPayload) (decision DecisionType, code string, err error)
}

// OctoBrain is the central implementation of GlobalOrchestratorSPI.
type OctoBrain struct {
	mu           sync.RWMutex
	llmProvider  FrontierLLMProvider
	hitlPending  map[string]*HITLRequest
	suspendedEnv map[string]*protocol.NervousEnvelope
}

// NewOctoBrain creates an initialized OctoBrain instance.
func NewOctoBrain(llm FrontierLLMProvider) *OctoBrain {
	return &OctoBrain{
		llmProvider:  llm,
		hitlPending:  make(map[string]*HITLRequest),
		suspendedEnv: make(map[string]*protocol.NervousEnvelope),
	}
}

func (b *OctoBrain) Plan(ctx context.Context, goal string, contextData map[string]any) (*PlanDAG, error) {
	if goal == "" {
		return nil, errors.New("brain: goal cannot be empty")
	}
	if b.llmProvider != nil {
		return b.llmProvider.GenerateDAG(ctx, goal)
	}

	// Deterministic fallback single-step plan
	return &PlanDAG{
		PlanID:    fmt.Sprintf("plan-%d", time.Now().UnixNano()),
		Goal:      goal,
		CreatedAt: time.Now(),
		Steps: []PlanStep{
			{
				StepID:           "step-1",
				TargetCapability: "distill-telemetry",
				Description:      "Process input telemetry and extract signals",
			},
		},
	}, nil
}

func (b *OctoBrain) Arbitrate(ctx context.Context, escalation *protocol.EscalationPayload) (*ArbitrationDecision, error) {
	if escalation == nil {
		return nil, errors.New("brain: escalation payload cannot be nil")
	}

	b.mu.Lock()
	defer b.mu.Unlock()

	// 1. If Gate 1 High Risk Mutation was triggered, immediately suspend for HITL approval
	if escalation.TriggeredGate == protocol.Gate1PreFlightPolicy && strings.TrimPrefix(escalation.FailureReason, "gate 1: high risk mutation blocked: ") == "prohibited destructive system command" {
		reqID := fmt.Sprintf("hitl-%d", time.Now().UnixNano())
		hitlReq := &HITLRequest{
			RequestID:   reqID,
			SessionID:   escalation.OriginalEnvelope.SessionID,
			Description: fmt.Sprintf("Dangerous command execution flagged: %s", escalation.FailureReason),
			RiskLevel:   "CRITICAL",
			ContextData: map[string]any{
				"escalation_id": escalation.EscalationID,
				"source_node":   escalation.OriginalEnvelope.SourceNode,
			},
			CreatedAt: time.Now(),
		}
		b.hitlPending[reqID] = hitlReq
		envCopy := escalation.OriginalEnvelope
		b.suspendedEnv[reqID] = &envCopy

		return &ArbitrationDecision{
			DecisionID:  fmt.Sprintf("dec-%d", time.Now().UnixNano()),
			Decision:    DecisionSuspendHITL,
			Reason:      "Escalated destructive action requires human authorization",
			HITLRequest: hitlReq,
		}, nil
	}

	// 2. Delegate to Frontier LLM if available
	if b.llmProvider != nil {
		dec, code, err := b.llmProvider.SolveEscalation(ctx, escalation)
		if err != nil {
			return nil, fmt.Errorf("brain: frontier LLM arbitration failed: %w", err)
		}
		return &ArbitrationDecision{
			DecisionID:          fmt.Sprintf("dec-%d", time.Now().UnixNano()),
			Decision:            dec,
			Reason:              "Frontier LLM synthesized resolution",
			SynthesizedToolCode: code,
			DynamicToolName:     "dynamic-remediation-script",
		}, nil
	}

	// 3. Deterministic rule-based arbitration fallback
	if escalation.TriggeredGate == protocol.Gate2VerifierFailed {
		// Synthesize dynamic patch script
		script := "#!/bin/bash\n# Synthesized remediation script\necho 'Remediating error via synthesized dynamic tool'"
		return &ArbitrationDecision{
			DecisionID:          fmt.Sprintf("dec-%d", time.Now().UnixNano()),
			Decision:            DecisionSynthesizeDynamicTool,
			Reason:              "Synthesized executable dynamic tool for repeated Gate 2 verifier failure",
			SynthesizedToolCode: script,
			DynamicToolName:     "dynamic-fix-script",
		}, nil
	}

	return &ArbitrationDecision{
		DecisionID: fmt.Sprintf("dec-%d", time.Now().UnixNano()),
		Decision:   DecisionAbort,
		Reason:     fmt.Sprintf("Unresolvable escalation: %s", escalation.FailureReason),
	}, nil
}

func (b *OctoBrain) SuspendForHITL(ctx context.Context, sessionID string, approvalReq *HITLRequest) error {
	b.mu.Lock()
	defer b.mu.Unlock()
	b.hitlPending[approvalReq.RequestID] = approvalReq
	return nil
}

func (b *OctoBrain) ResumeFromHITL(ctx context.Context, requestID string, approved bool, feedback string) (*protocol.NervousEnvelope, error) {
	b.mu.Lock()
	defer b.mu.Unlock()

	req, exists := b.hitlPending[requestID]
	if !exists {
		return nil, fmt.Errorf("brain: hitl request not found: %s", requestID)
	}

	env, envExists := b.suspendedEnv[requestID]
	delete(b.hitlPending, requestID)
	delete(b.suspendedEnv, requestID)

	if !approved {
		return nil, fmt.Errorf("brain: hitl approval rejected: %s", feedback)
	}

	if envExists && env != nil {
		env.Parameters["hitl_approved"] = true
		env.Parameters["hitl_request_id"] = req.RequestID
		env.Parameters["hitl_feedback"] = feedback
		return env, nil
	}

	return nil, nil
}
